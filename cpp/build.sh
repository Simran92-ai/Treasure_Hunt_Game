#!/bin/sh
# Rebuild the level generator.  Needs clang with the wasm32 target + wasm-ld.
# Output: ../src/js/level/levelgen_wasm.js  (wasm embedded as base64 so the game still
# runs from file:// with no server and no fetch()).
set -e
cd "$(dirname "$0")"
clang --target=wasm32 -O2 -std=c++17 -nostdlib -fno-builtin -fno-exceptions -fno-rtti \
  -Wl,--no-entry -Wl,--export=grid_ptr -Wl,--export=reserve_ptr -Wl,--export=dist_ptr -Wl,--export=out_ptr -Wl,--export=set_seed -Wl,--export=next_rand -Wl,--export=set_size -Wl,--export=count_components -Wl,--export=ensure_connected -Wl,--export=bsp_rooms -Wl,--export=add_doors -Wl,--export=scatter -Wl,--export=bfs_start -Wl,--export=pick_points -Wl,--export=patrol_pairs -Wl,-z,stack-size=65536 \
  -Wl,--initial-memory=262144 -Wl,--max-memory=262144 \
  -o levelgen.wasm levelgen.cpp
node -e "
const fs=require('fs');
const b=fs.readFileSync('levelgen.wasm').toString('base64');
fs.writeFileSync('../src/js/level/levelgen_wasm.js','/* generated by cpp/build.sh - do not edit */\nwindow.TH=window.TH||{};TH.LEVELGEN_WASM_B64=\"'+b+'\";\n');
console.log('wasm bytes',fs.statSync('levelgen.wasm').size);
"
